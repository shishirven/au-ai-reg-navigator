"""Staging run for statement-level authority (D-044). Does NOT touch the live index.

    uv run python scripts/authority_staging.py

1. builds chroma_staging/ from data/sources.yaml + data/sources_pending.yaml (adds the Privacy Act
   statutory extracts);
2. tags every statement of every current chunk; resolves every legal reference;
3. demos retrieval + authority for the APP 1.7 question and the small business exemption;
4. exports a stratified clause sample for human labelling (labels hidden from the labeller);
5. writes docs/authority_staging_report.md.
"""

from __future__ import annotations

import csv
import json
import random
import shutil
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

import yaml

from regnav.config import load_config
from regnav.ingest.index import ingest, load_chunk_rows
from regnav.legal.applicability import Profile, assess
from regnav.legal.references import Resolver
from regnav.legal.statements import split_statements
from regnav.legal.tagger import LABELS, classify
from regnav.retrieve import build_retrieval

STAGING = Path("chroma_staging")
SAMPLE_CSV = Path("data/eval/clause_labels.csv")
PREDICTIONS = Path("data/eval/clause_tagger_predictions.jsonl")
REPORT = Path("docs/authority_staging_report.md")
TODAY = date(2026, 11, 19)


def build_staging_index():
    STAGING.mkdir(exist_ok=True)
    live = yaml.safe_load(Path("data/sources.yaml").read_text())
    pending = yaml.safe_load(Path("data/sources_pending.yaml").read_text())
    merged = STAGING / "sources_staging.yaml"
    merged.write_text(
        yaml.safe_dump({"documents": live["documents"] + pending["documents"]}, sort_keys=False)
    )
    cfg = load_config("configs/hybrid_stratified_rerank.yaml", name="staging_authority")
    cfg.paths.chroma_dir = STAGING
    cfg.paths.sources_file = merged
    report = ingest(cfg, write_sources=False)
    return cfg, report


def tag_corpus(rows):
    tagged = []
    for r in rows:
        if r["status"] != "current":
            continue
        for st in split_statements(r["chunk_id"], r["text"]):
            tag = classify(st.text, r["tier"], st.context)
            tagged.append({"row": r, "st": st, "tag": tag})
    return tagged


def sample_for_labelling(tagged, n=150, seed=42):
    """Stratified by (document, predicted label) so rare labels are represented. Statements shorter
    than 6 words are skipped (headings/fragments)."""
    rng = random.Random(seed)
    cells = defaultdict(list)
    for t in tagged:
        if len(t["st"].text.split()) >= 6:
            cells[(t["row"]["doc_id"], t["tag"].label)].append(t)
    keys = sorted(cells)
    picked = []
    while len(picked) < n and any(cells[k] for k in keys):
        for k in keys:
            if cells[k] and len(picked) < n:
                picked.append(cells[k].pop(rng.randrange(len(cells[k]))))
    rng.shuffle(picked)
    return picked


def main() -> int:
    cfg, ing = build_staging_index()
    rows = load_chunk_rows(cfg)
    resolver = Resolver(rows)
    tagged = tag_corpus(rows)

    lines = [
        "# Statement-level authority - staging report",
        "",
        f"Staging index `{ing.index_version}` (live index unchanged). Built from `data/sources.yaml` + "
        "`data/sources_pending.yaml`. Generated by `scripts/authority_staging.py`.",
        "",
    ]

    # 1. label distribution per document
    by_doc = defaultdict(Counter)
    for t in tagged:
        by_doc[t["row"]["doc_id"]][t["tag"].label] += 1
    lines += [
        "## 1. Statement labels per document (rule-based tagger)",
        "",
        "| document | tier | statements | " + " | ".join(LABELS) + " |",
        "|---|---|---|" + "---|" * len(LABELS),
    ]
    tiers = {r["doc_id"]: r["tier"] for r in rows}
    for d in sorted(by_doc):
        c = by_doc[d]
        lines.append(
            f"| `{d}` | {tiers[d]} | {sum(c.values())} | "
            + " | ".join(str(c[label] or "") for label in LABELS)
            + " |"
        )

    # 2. reference resolution
    ref_stats = Counter()
    unresolved = Counter()
    restate_resolved = Counter()
    for t in tagged:
        for ref in t["tag"].refs:
            res = resolver.resolve(ref)
            if res.resolved:
                ref_stats["resolved to chunk"] += 1
            elif res.doc_id and res.in_corpus:
                ref_stats["instrument in corpus, provision not located"] += 1
            else:
                ref_stats["not in corpus"] += 1
                unresolved[ref.instrument] += 1
        if t["tag"].label == "restates_law":
            ok = any(resolver.resolve(r).resolved for r in t["tag"].refs)
            restate_resolved[
                "linked to a provision in corpus"
                if ok
                else ("cites law not in corpus" if t["tag"].refs else "no citation")
            ] += 1
    lines += ["", "## 2. Legal references", "", "| outcome | count |", "|---|---|"] + [
        f"| {k} | {v} |" for k, v in ref_stats.most_common()
    ]
    lines += [
        "",
        "Most-cited instruments **not in the corpus**: "
        + ", ".join(f"{k} ({v})" for k, v in unresolved.most_common(12)),
        "",
        "`restates_law` statements: "
        + ", ".join(f"{k}: {v}" for k, v in restate_resolved.most_common()),
    ]

    # 3. demo: APP question on the staging index
    rs = build_retrieval(cfg)
    q = "When does the APP 1.7-1.9 automated decision-making transparency obligation commence?"
    chunks = rs.search(q, sector="bank")
    lines += [
        "",
        "## 3. Demo: the APP 1.7 question on the staging index",
        "",
        f"Question: *{q}* (sector: bank)",
        "",
        "| rank | chunk | tier | top statement label | references resolved to |",
        "|---|---|---|---|---|",
    ]
    for c in chunks[:8]:
        sts = split_statements(c.chunk_id, c.text)
        tags = [classify(s.text, c.tier, s.context) for s in sts]
        main = Counter(t.label for t in tags).most_common(1)[0][0] if tags else "-"
        links = sorted({cid for t in tags for r in t.refs for cid in resolver.resolve(r).chunk_ids})
        lines.append(
            f"| {c.rank} | `{c.chunk_id}` | {c.tier} | {main} | {', '.join(links[:3]) or '-'} |"
        )

    # 4. applicability demo
    profiles = {
        "Bank (APRA-regulated)": Profile(sector="bank"),
        "Any business, turnover > $3m": Profile(sector="any_business", turnover_over_3m=True),
        "Any business, turnover <= $3m": Profile(sector="any_business", turnover_over_3m=False),
        "Small business that trades in personal information": Profile(
            sector="any_business", turnover_over_3m=False, exceptions={"trades_in_personal_info"}
        ),
        "Any business, turnover not stated": Profile(sector="any_business"),
    }
    lines += [
        "",
        "## 4. Binding on whom, and from when: APP 1.7 (privacy) vs CPS 230 para 52 (prudential)",
        "",
        f"As at {TODAY.isoformat()}.",
        "",
        "| profile | APP 1.7 (statute) | CPS 230 para 52 |",
        "|---|---|---|",
    ]
    for name, p in profiles.items():
        app = assess(
            regime="privacy",
            doc_tier="binding",
            status="current",
            effective_from="2026-12-10",
            applies_to_sector=True,
            profile=p,
            today=TODAY,
        )
        cps = assess(
            regime="prudential",
            doc_tier="binding",
            status="current",
            effective_from="2026-07-01",
            applies_to_sector=p.sector in ("bank", "insurer", "super"),
            profile=p,
            today=TODAY,
        )
        lines.append(
            f"| {name} | **{app.status}**: {app.reason} | **{cps.status}**: {cps.reason} |"
        )

    # 5. clause sample for human labelling
    picked = sample_for_labelling(tagged)
    SAMPLE_CSV.parent.mkdir(parents=True, exist_ok=True)
    with SAMPLE_CSV.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(
            ["statement_id", "document", "doc_tier", "lead_in", "statement", "human_label", "notes"]
        )
        for t in picked:
            st = t["st"]
            w.writerow(
                [
                    f"{st.chunk_id}#{st.index}",
                    t["row"]["short_name"],
                    t["row"]["tier"],
                    st.context,
                    st.text,
                    "",
                    "",
                ]
            )
    with PREDICTIONS.open("w") as f:
        for t in picked:
            st = t["st"]
            f.write(
                json.dumps(
                    {
                        "statement_id": f"{st.chunk_id}#{st.index}",
                        "label": t["tag"].label,
                        "confidence": t["tag"].confidence,
                        "evidence": t["tag"].evidence,
                    }
                )
                + "\n"
            )
    lines += [
        "",
        "## 5. Clause sample for validation",
        "",
        f"{len(picked)} statements exported to `{SAMPLE_CSV}` (stratified by document x predicted label; the "
        f"predictions are kept separately in `{PREDICTIONS}` so the labeller is not anchored). Label "
        "distribution of the sample (predicted): "
        + ", ".join(f"{k} {v}" for k, v in Counter(t["tag"].label for t in picked).most_common())
        + ".",
    ]
    REPORT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    shutil.rmtree(STAGING / "tmp", ignore_errors=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

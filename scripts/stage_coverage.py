"""Stage coverage on broad questions (D-052): does the context reach every part a complete answer
needs? Retrieval only, no LLM, no quota.

Each question in data/eval/broad_questions_draft.jsonl lists *groups* (the parts of a complete
answer, e.g. "notify APRA (CPS 230 para 60)"), each a set of chunk ids or ``doc:<doc_id>``. A group
is covered if any of its members reaches the context. DRAFT: groups written by the developer.

Usage: uv run python scripts/stage_coverage.py configs/a.yaml configs/b.yaml ...
Writes docs/stage_coverage.md.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from regnav.config import load_config
from regnav.eval.stats import bootstrap_ci
from regnav.retrieve import build_retrieval

QUESTIONS = Path("data/eval/broad_questions_draft.jsonl")
OUT = Path("docs/stage_coverage.md")


def covered(member: str, ids: set[str], docs: set[str]) -> bool:
    return member.split(":", 1)[1] in docs if member.startswith("doc:") else member in ids


def run(config_path: str, qs: list[dict]) -> tuple[str, list[dict]]:
    cfg = load_config(config_path)
    system = build_retrieval(cfg)
    rows = []
    for q in qs:
        hits = system.search(q["question"], sector=q.get("sector"))
        ids = {h.chunk_id for h in hits}
        docs = {str(h.metadata.get("doc_id")) for h in hits}
        got = {g: any(covered(m, ids, docs) for m in members) for g, members in q["groups"].items()}
        rows.append(
            {"id": q["id"], "coverage": sum(got.values()) / len(got), "groups": got, "n": len(hits)}
        )
    return cfg.name, rows


def main(argv: list[str]) -> int:
    qs = [json.loads(line) for line in QUESTIONS.read_text().splitlines() if line.strip()]
    results = [run(c, qs) for c in argv]
    names = [n for n, _ in results]
    lines = [
        "# Stage coverage on broad questions (DRAFT)",
        "",
        "Share of the parts of a complete answer (groups) that reach the model's context. "
        f"{len(qs)} developer-written broad questions in `{QUESTIONS}`; retrieval only. "
        "Generated by `scripts/stage_coverage.py`.",
        "",
        "| question | " + " | ".join(f"`{n}`" for n in names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for i, q in enumerate(qs):
        cells = [f"{rows[i]['coverage']:.2f}" for _, rows in results]
        lines.append(
            f"| {q['id']} {q['question'][:70]}{'…' if len(q['question']) > 70 else ''} | "
            + " | ".join(cells)
            + " |"
        )
    means = []
    for _, rows in results:
        vals = [r["coverage"] for r in rows]
        point, lo, hi = bootstrap_ci(vals, lambda xs: sum(xs) / len(xs))
        means.append(f"**{point:.2f}** [{lo:.2f}, {hi:.2f}]")
    lines.append("| **mean [95% CI]** | " + " | ".join(means) + " |")
    lines += ["", "### Groups missed", ""]
    for name, rows in results:
        missed = [f"{r['id']}: {g}" for r in rows for g, ok in r["groups"].items() if not ok]
        lines.append(f"- `{name}`: " + ("; ".join(missed) if missed else "none"))
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
